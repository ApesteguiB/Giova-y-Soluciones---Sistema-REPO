CREATE TABLE tender_sources (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    code VARCHAR(40) NOT NULL,
    base_url VARCHAR(2048) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    last_successful_at DATETIME(6) NULL,
    cursor_value VARCHAR(4096) NULL,
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_tender_sources_public_id (public_id),
    UNIQUE KEY uk_tender_sources_code (code),
    KEY ix_tender_sources_enabled (enabled, code),
    CONSTRAINT ck_tender_sources_code CHECK (CHAR_LENGTH(code) > 0),
    CONSTRAINT ck_tender_sources_base_url CHECK (CHAR_LENGTH(base_url) > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE tender_sync_runs (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    source_id BIGINT NOT NULL,
    trigger_type VARCHAR(12) NOT NULL,
    requested_by_worker_id BIGINT NULL,
    started_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    finished_at DATETIME(6) NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'RUNNING',
    cursor_before VARCHAR(4096) NULL,
    cursor_after VARCHAR(4096) NULL,
    pages_count INT UNSIGNED NOT NULL DEFAULT 0,
    releases_count INT UNSIGNED NOT NULL DEFAULT 0,
    upserts_count INT UNSIGNED NOT NULL DEFAULT 0,
    matches_count INT UNSIGNED NOT NULL DEFAULT 0,
    error_code VARCHAR(60) NULL,
    error_message VARCHAR(500) NULL,
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_tender_sync_runs_public_id (public_id),
    KEY ix_tender_sync_runs_source_status (source_id, status, started_at, id),
    KEY ix_tender_sync_runs_started (started_at, id),
    CONSTRAINT fk_tender_sync_runs_source FOREIGN KEY (source_id) REFERENCES tender_sources(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_tender_sync_runs_worker FOREIGN KEY (requested_by_worker_id) REFERENCES workers(id) ON UPDATE RESTRICT ON DELETE SET NULL,
    CONSTRAINT ck_tender_sync_runs_trigger CHECK (trigger_type IN ('SCHEDULED','MANUAL')),
    CONSTRAINT ck_tender_sync_runs_status CHECK (status IN ('RUNNING','SUCCEEDED','FAILED')),
    CONSTRAINT ck_tender_sync_runs_dates CHECK (finished_at IS NULL OR finished_at >= started_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE tender_releases (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    source_id BIGINT NOT NULL,
    release_id VARCHAR(255) NOT NULL,
    ocid VARCHAR(255) NOT NULL,
    published_date DATETIME(6) NOT NULL,
    release_tag VARCHAR(255) NULL,
    source_url VARCHAR(2048) NULL,
    source_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    raw_json LONGTEXT NOT NULL,
    first_seen_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    last_seen_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_tender_releases_public_id (public_id),
    UNIQUE KEY uk_tender_releases_source_release (source_id, release_id),
    KEY ix_tender_releases_source_ocid_date (source_id, ocid, published_date, id),
    KEY ix_tender_releases_published (published_date, id),
    CONSTRAINT fk_tender_releases_source FOREIGN KEY (source_id) REFERENCES tender_sources(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_tender_releases_source_hash CHECK (CHAR_LENGTH(source_hash) = 64)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE tender_processes (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    source_id BIGINT NOT NULL,
    ocid VARCHAR(255) NOT NULL,
    title VARCHAR(500) NOT NULL,
    description VARCHAR(4000) NULL,
    buyer_id VARCHAR(255) NULL,
    buyer_name VARCHAR(255) NULL,
    region VARCHAR(255) NULL,
    classification_codes LONGTEXT NULL,
    procurement_method VARCHAR(100) NULL,
    status VARCHAR(60) NULL,
    currency_code CHAR(3) NULL,
    amount DECIMAL(19,4) NULL,
    tender_start DATETIME(6) NULL,
    tender_end DATETIME(6) NULL,
    official_url VARCHAR(2048) NULL,
    latest_release_date DATETIME(6) NOT NULL,
    source_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_tender_processes_public_id (public_id),
    UNIQUE KEY uk_tender_processes_source_ocid (source_id, ocid),
    KEY ix_tender_processes_source_latest (source_id, latest_release_date, id),
    KEY ix_tender_processes_buyer_region (buyer_name, region, id),
    KEY ix_tender_processes_tender_end (tender_end, id),
    CONSTRAINT fk_tender_processes_source FOREIGN KEY (source_id) REFERENCES tender_sources(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_tender_processes_amount CHECK (amount IS NULL OR amount >= 0),
    CONSTRAINT ck_tender_processes_currency CHECK (currency_code IS NULL OR CHAR_LENGTH(currency_code) = 3),
    CONSTRAINT ck_tender_processes_dates CHECK (tender_end IS NULL OR tender_start IS NULL OR tender_end >= tender_start)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE tender_match_profiles (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    name VARCHAR(180) NOT NULL,
    include_keywords LONGTEXT NOT NULL,
    exclude_keywords LONGTEXT NOT NULL,
    buyers LONGTEXT NOT NULL,
    regions LONGTEXT NOT NULL,
    classification_codes LONGTEXT NOT NULL,
    min_amount DECIMAL(19,4) NULL,
    max_amount DECIMAL(19,4) NULL,
    closing_from DATE NULL,
    closing_to DATE NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_tender_match_profiles_public_id (public_id),
    KEY ix_tender_match_profiles_active_updated (active, updated_at, id),
    CONSTRAINT ck_tender_match_profiles_amounts CHECK ((min_amount IS NULL OR min_amount >= 0) AND (max_amount IS NULL OR max_amount >= 0) AND (min_amount IS NULL OR max_amount IS NULL OR max_amount >= min_amount)),
    CONSTRAINT ck_tender_match_profiles_closing CHECK (closing_to IS NULL OR closing_from IS NULL OR closing_to >= closing_from)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE tender_matches (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    process_id BIGINT NOT NULL,
    profile_id BIGINT NOT NULL,
    owner_worker_id BIGINT NULL,
    score SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    reasons LONGTEXT NOT NULL,
    state VARCHAR(12) NOT NULL DEFAULT 'NEW',
    matched_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_tender_matches_public_id (public_id),
    UNIQUE KEY uk_tender_matches_process_profile (process_id, profile_id),
    KEY ix_tender_matches_state_score (state, score, matched_at, id),
    KEY ix_tender_matches_owner_state (owner_worker_id, state, id),
    KEY ix_tender_matches_profile_score (profile_id, score, id),
    CONSTRAINT fk_tender_matches_process FOREIGN KEY (process_id) REFERENCES tender_processes(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_tender_matches_profile FOREIGN KEY (profile_id) REFERENCES tender_match_profiles(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_tender_matches_owner FOREIGN KEY (owner_worker_id) REFERENCES workers(id) ON UPDATE RESTRICT ON DELETE SET NULL,
    CONSTRAINT ck_tender_matches_score CHECK (score BETWEEN 0 AND 100),
    CONSTRAINT ck_tender_matches_state CHECK (state IN ('NEW','REVIEWING','FOLLOWING','DISMISSED','CLOSED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE tender_match_actions (
    id BIGINT NOT NULL AUTO_INCREMENT,
    action_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    match_id BIGINT NOT NULL,
    actor_worker_id BIGINT NOT NULL,
    action_code VARCHAR(20) NOT NULL,
    note VARCHAR(500) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_tender_match_actions_action_id (action_id),
    KEY ix_tender_match_actions_match_created (match_id, created_at, id),
    KEY ix_tender_match_actions_actor_created (actor_worker_id, created_at, id),
    CONSTRAINT fk_tender_match_actions_match FOREIGN KEY (match_id) REFERENCES tender_matches(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_tender_match_actions_actor FOREIGN KEY (actor_worker_id) REFERENCES workers(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_tender_match_actions_code CHECK (action_code IN ('REVIEW','FOLLOW','DISMISS','CLOSE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

