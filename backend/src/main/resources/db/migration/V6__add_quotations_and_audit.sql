CREATE TABLE document_sequences (
    document_type VARCHAR(30) NOT NULL,
    year SMALLINT UNSIGNED NOT NULL,
    last_value BIGINT UNSIGNED NOT NULL DEFAULT 0,
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (document_type, year),
    CONSTRAINT ck_document_sequences_value CHECK (last_value >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE quotations (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    quotation_number VARCHAR(30) NULL,
    customer_id BIGINT NOT NULL,
    owner_worker_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    issued_at DATETIME(6) NULL,
    valid_until DATE NULL,
    currency_code CHAR(3) NOT NULL,
    exchange_rate_to_pen DECIMAL(19,6) NOT NULL DEFAULT 1,
    includes_tax BOOLEAN NOT NULL DEFAULT FALSE,
    tax_rate DECIMAL(9,6) NOT NULL DEFAULT 0,
    subtotal_amount DECIMAL(19,4) NOT NULL DEFAULT 0,
    tax_amount DECIMAL(19,4) NOT NULL DEFAULT 0,
    total_amount DECIMAL(19,4) NOT NULL DEFAULT 0,
    notes VARCHAR(1500) NULL,
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_quotations_public_id (public_id),
    UNIQUE KEY uk_quotations_number (quotation_number),
    KEY ix_quotations_owner_status (owner_worker_id, status, updated_at, id),
    KEY ix_quotations_customer_status (customer_id, status, updated_at, id),
    CONSTRAINT fk_quotations_customer FOREIGN KEY (customer_id) REFERENCES customers(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_quotations_owner FOREIGN KEY (owner_worker_id) REFERENCES workers(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_quotations_status CHECK (status IN ('DRAFT','ISSUED','ACCEPTED','REJECTED','EXPIRED','CANCELLED')),
    CONSTRAINT ck_quotations_currency CHECK (currency_code IN ('PEN','USD')),
    CONSTRAINT ck_quotations_exchange CHECK (exchange_rate_to_pen > 0),
    CONSTRAINT ck_quotations_tax_rate CHECK (tax_rate >= 0 AND tax_rate <= 1),
    CONSTRAINT ck_quotations_amounts CHECK (subtotal_amount >= 0 AND tax_amount >= 0 AND total_amount >= 0),
    CONSTRAINT ck_quotations_issued_at CHECK (status = 'DRAFT' OR issued_at IS NOT NULL),
    CONSTRAINT ck_quotations_validity CHECK (valid_until IS NULL OR issued_at IS NULL OR valid_until >= DATE(issued_at))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE quotation_items (
    id BIGINT NOT NULL AUTO_INCREMENT,
    quotation_id BIGINT NOT NULL,
    line_number INT NOT NULL,
    product_id BIGINT NULL,
    sku_snapshot VARCHAR(80) NULL,
    description_snapshot VARCHAR(500) NOT NULL,
    unit_snapshot VARCHAR(30) NOT NULL DEFAULT 'unidad',
    quantity DECIMAL(19,4) NOT NULL,
    unit_price DECIMAL(19,4) NOT NULL,
    line_subtotal DECIMAL(19,4) NOT NULL,
    line_tax DECIMAL(19,4) NOT NULL,
    line_total DECIMAL(19,4) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_quotation_items_line (quotation_id, line_number),
    KEY ix_quotation_items_product (product_id),
    CONSTRAINT fk_quotation_items_quotation FOREIGN KEY (quotation_id) REFERENCES quotations(id) ON UPDATE RESTRICT ON DELETE CASCADE,
    CONSTRAINT fk_quotation_items_product FOREIGN KEY (product_id) REFERENCES products(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_quotation_items_line CHECK (line_number > 0),
    CONSTRAINT ck_quotation_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_quotation_items_price CHECK (unit_price >= 0),
    CONSTRAINT ck_quotation_items_amounts CHECK (line_subtotal >= 0 AND line_tax >= 0 AND line_total >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE quotation_documents (
    quotation_id BIGINT NOT NULL,
    document_id BIGINT NOT NULL,
    document_role VARCHAR(30) NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (quotation_id, document_id),
    UNIQUE KEY uk_quotation_documents_issued (quotation_id, document_role),
    CONSTRAINT fk_quotation_documents_quotation FOREIGN KEY (quotation_id) REFERENCES quotations(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_quotation_documents_document FOREIGN KEY (document_id) REFERENCES stored_documents(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_quotation_documents_role CHECK (document_role IN ('ISSUED_PDF','ATTACHMENT'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE audit_events (
    id BIGINT NOT NULL AUTO_INCREMENT,
    event_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    actor_worker_id BIGINT NULL,
    role_snapshot VARCHAR(20) NULL,
    action VARCHAR(60) NOT NULL,
    entity_type VARCHAR(60) NULL,
    entity_id VARCHAR(80) NULL,
    result VARCHAR(10) NOT NULL,
    request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    ip_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    summary VARCHAR(2000) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_audit_events_event_id (event_id),
    KEY ix_audit_events_created (created_at, id),
    KEY ix_audit_events_entity (entity_type, entity_id, created_at),
    CONSTRAINT fk_audit_events_actor FOREIGN KEY (actor_worker_id) REFERENCES workers(id) ON UPDATE RESTRICT ON DELETE SET NULL,
    CONSTRAINT ck_audit_events_result CHECK (result IN ('SUCCESS','FAILURE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
